#!/usr/bin/env python3
"""Generate distribution metadata from VERSION; --check detects every stale copy."""
import argparse
import json
from pathlib import Path
import re
import sys
ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ['01_molecule_generation/src', '02_docking/src/sbvs', '02_docking/src/sbvs2',
            '03_virtual_screening/src/zvss', '05_molecular_dynamics/modules/automation']

def generated():
    version = (ROOT / 'VERSION').read_text().strip()
    files = {ROOT / p / '_platform_version.py': '# Generated by deployment/sync_platform_version.py from VERSION. Do not edit.\n__version__ = ' + repr(version) + '\n' for p in PACKAGES}
    for path in ('02_docking/pyproject.toml', '03_virtual_screening/pyproject.toml'):
        p = ROOT / path; package = 'sbvs2' if path.startswith('02') else 'zvss'
        text = re.sub(r'^version = "[^"]+"\n', 'dynamic = ["version"]\n', p.read_text(), flags=re.M)
        if '[tool.setuptools.dynamic]' not in text:
            text += '\n[tool.setuptools.dynamic]\nversion = {attr = "' + package + '._platform_version.__version__"}\n'
        files[p] = text
    path = ROOT / '06_websites/01_public_demo/yuanhe-public/package.json'
    value = json.loads(path.read_text()); value['version'] = version
    files[path] = json.dumps(value, indent=2) + '\n'
    files[path.parent / 'src/platform-version.json'] = json.dumps({'product': 'Yuanhe Bio Platform', 'software_version': version, 'mode': 'static_demo'}, indent=2) + '\n'
    base = 'https://github.com/lzylumos-sudo/yuanhe-bio-workflow'
    tag = 'v' + version
    archive = 'yuanhe-bio-platform-' + version + '.zip'
    release = {'software_version': version, 'tag': tag, 'channel': 'development' if '-' in version else 'release',
               'release_url': base + '/releases/tag/' + tag,
               'download_url': base + '/releases/download/' + tag + '/' + archive,
               'checksums_url': base + '/releases/download/' + tag + '/SHA256SUMS.txt'}
    files[ROOT / 'deployment/current_release.json'] = json.dumps(release, indent=2) + '\n'
    block = ('<!-- current-release:start -->\n'
             '**Current administrator build: ' + version + ' (' + release['channel'] + ')**\n\n'
             '[Download current package](' + release['download_url'] + ') · '
             '[Install and verify](DEPLOY.md) · [Release notes](' + release['release_url'] + ') · '
             '[Historical versions](docs/releases/HISTORY.md)\n\n'
             'The package includes version and source-hash records. Target-machine acceptance remains required.\n'
             '<!-- current-release:end -->')
    readme = ROOT / 'README.md'
    text, count = re.subn(r'<!-- current-release:start -->.*?<!-- current-release:end -->', block, readme.read_text(), flags=re.S)
    if count != 1: raise ValueError('README must contain exactly one current-release block')
    files[readme] = text
    citation = ROOT / 'CITATION.cff'
    text = re.sub(r'^version:.*\n', '', citation.read_text(), flags=re.M)
    files[citation] = text + 'version: "' + version + '"\n'
    return files

def main():
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); args = p.parse_args()
    stale = []
    for path, text in generated().items():
        if not path.exists() or path.read_text() != text:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check: path.write_text(text)
    print(json.dumps({'stale' if args.check else 'updated': stale}))
    return int(args.check and bool(stale))
if __name__ == '__main__': raise SystemExit(main())
