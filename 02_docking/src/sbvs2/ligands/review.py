"""2D state review: RDKit-generated SVG with real per-atom charges (plan §15). No generative images."""
from __future__ import annotations
from rdkit import Chem
from rdkit.Chem import AllChem
from rdkit.Chem.Draw import rdMolDraw2D

# conditions that can never be bulk-approved
HARD_BLOCKS = {"CHARGE_ERROR", "EMBED_FAILED", "NOT_CONVERGED"}


def state_svg(smiles: str, charges: list | None = None, size=(360, 260)) -> str:
    m = Chem.MolFromSmiles(smiles)
    AllChem.Compute2DCoords(m)
    d = rdMolDraw2D.MolDraw2DSVG(*size)
    opts = d.drawOptions(); opts.addAtomIndices = True; opts.addStereoAnnotation = True
    d.DrawMolecule(m)
    d.FinishDrawing()
    return d.GetDrawingText()


def bulk_approvable(state: dict, rule: dict) -> tuple[bool, str]:
    """A saved user rule can pass only anomaly-free states. Returns (ok, why_not)."""
    if state.get("status") == "BLOCKED" or state.get("block_reason") in HARD_BLOCKS:
        return False, "hard_error"
    if state.get("truncated"):
        return False, "truncated_enumeration"
    if state.get("stereo_note") == "enumerated_unknown_centers":
        return False, "unknown_stereo"
    ch = state.get("charges", {}).get("check", {})
    if not ch.get("pass"):
        return False, "charge_check"
    if abs(state.get("formal_charge", 0)) > rule.get("max_abs_formal_charge", 1):
        return False, "formal_charge_outside_rule"
    if rule.get("require_ph_confirmed", True) and not state.get("ph_confirmed"):
        return False, "ph_not_confirmed"
    return True, ""


def _escape(t):
    return str(t).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render_review_svg(rec: dict, parent_smiles: str | None, size=(520, 380)) -> str:
    """Real RDKit 2D depiction of THIS state: formal charges drawn on atoms, Gasteiger partial charge per heavy atom,
    polar hydrogens explicit, stereo labels (CIP) and bold highlight of atoms whose charge/H count differs from the parent.
    Text panel lists method, pH window, warnings. Nothing here is generated by a model: only RDKit output + recorded fields."""
    m = Chem.MolFromSmiles(rec["smiles"])
    if m is None:
        return f'<svg xmlns="http://www.w3.org/2000/svg" width="{size[0]}" height="60"><text x="8" y="30" fill="#b00">UNRENDERABLE: {_escape(rec["smiles"])}</text></svg>'
    q = (rec.get("charges") or {}).get("values")
    # map partial charges (indexed on the H-added 3D mol) onto heavy atoms of the SMILES graph by canonical ranking
    mh = rec.get("_mol")
    labels = {}
    if mh is not None and q:
        heavy = Chem.RemoveHs(Chem.Mol(mh))
        mt = heavy.GetSubstructMatch(m)   # indices of `heavy` atoms in the order of `m`
        if mt and len(mt) == m.GetNumAtoms():
            for i_m, i_h in enumerate(mt):
                # sum partial charge of heavy atom + its hydrogens (what a reader means by "charge on the group")
                a = mh.GetAtomWithIdx(i_h)
                tot = q[i_h] + sum(q[n.GetIdx()] for n in a.GetNeighbors() if n.GetAtomicNum() == 1)
                labels[i_m] = tot
    hl, diff = [], []
    if parent_smiles:
        pm = Chem.MolFromSmiles(parent_smiles)
        if pm is not None and pm.GetNumAtoms() == m.GetNumAtoms():
            for a, b in zip(m.GetAtoms(), pm.GetAtoms()):
                if a.GetFormalCharge() != b.GetFormalCharge() or a.GetTotalNumHs() != b.GetTotalNumHs():
                    hl.append(a.GetIdx()); diff.append(a.GetIdx())
    Chem.rdCIPLabeler.AssignCIPLabels(m)
    AllChem.Compute2DCoords(m)
    panel_h = 120
    d = rdMolDraw2D.MolDraw2DSVG(size[0], size[1] - panel_h, -1, -1, True)   # noFreetype: labels stay real <text>
    o = d.drawOptions(); o.addStereoAnnotation = True; o.addAtomIndices = False
    for i, v in labels.items():
        a = m.GetAtomWithIdx(i)
        if a.GetAtomicNum() > 1:
            a.SetProp("atomNote", f"{v:+.2f}")
    o.annotationFontScale = 0.6
    # explicit polar H: show N-H / O-H counts via atom labels
    for a in m.GetAtoms():
        if a.GetAtomicNum() in (7, 8, 16) and a.GetTotalNumHs() > 0:
            a.SetProp("_displayLabel", f"{a.GetSymbol()}H{a.GetTotalNumHs() if a.GetTotalNumHs() > 1 else ''}" if a.GetFormalCharge() == 0 else "")
    d.DrawMolecule(m, highlightAtoms=hl, highlightAtomColors={i: (1.0, 0.85, 0.3) for i in hl})
    d.FinishDrawing()
    body = d.GetDrawingText()
    body = body[body.index("<rect"):body.rindex("</svg>")] if "<rect" in body else ""
    warn = []
    if rec.get("truncated"): warn.append("枚举被截断(未穷举)")
    if rec.get("stereo_note") == "enumerated_unknown_centers": warn.append("立体未指定,已枚举:需人工确认")
    if rec.get("conformer_status") != "OK": warn.append(f"构象: {rec.get('conformer_status')}")
    if rec.get("status") == "BLOCKED": warn.append(f"BLOCKED: {rec.get('block_reason')}")
    chk = (rec.get("charges") or {}).get("check") or {}
    if chk and not chk.get("pass"): warn.append("电荷检查未通过")
    if not rec.get("ph_confirmed"): warn.append("pH 未经用户确认")
    lines = [f'state {rec["state_id"]}  formal charge {rec["formal_charge"]:+d}  parent {rec["parent_id"]}',
             f'method {rec.get("method")}  pH {rec.get("ph_range")}  charges {(rec.get("charges") or {}).get("method")} (sum check {chk.get("abs_diff")})',
             f'why: {rec.get("evidence", "")}   stereo: {rec.get("stereo_note", "specified")}',
             "黄色高亮 = 相对母体电荷/H数改变;原子旁数字 = Gasteiger 部分电荷(含所连H)",
             "警告: " + ("; ".join(warn) if warn else "无")]
    y0 = size[1] - panel_h + 16
    txt = "".join(f'<text x="8" y="{y0 + 17*i}" font-family="monospace" font-size="11" fill="{"#a00" if (i==4 and warn) else "#222"}">{_escape(t)}</text>' for i, t in enumerate(lines))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{size[0]}" height="{size[1]}" viewBox="0 0 {size[0]} {size[1]}">'
            f'<rect width="100%" height="100%" fill="white"/>{body}{txt}</svg>')
