"""Verified original identifiers for built topology and residue-level analysis.

Call immediately after build, before dynamics, and again after analysis. Only
standard-library code is used. No coordinate/name proximity guessing is allowed.
Protein hydrogens are regenerated by the v2 preparation adapter: same-name
hydrogens are not falsely presented as the same original atom.
"""
from __future__ import annotations
from collections import defaultdict
import csv
import hashlib
import json
import math
from pathlib import Path
import uuid


class MappingError(ValueError):
    pass


def _require(condition, message):
    if not condition:
        raise MappingError(message)


def _read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + "." + uuid.uuid4().hex + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")
    temporary.replace(path)


def _pdb_atoms(path):
    atoms = []
    for line_number, raw in enumerate(Path(path).read_text().splitlines(), 1):
        if raw[:6].strip() not in {"ATOM", "HETATM"}:
            continue
        line = raw.ljust(80)
        try:
            xyz = [float(line[i:i + 8]) for i in (30, 38, 46)]
        except ValueError as exc:
            raise MappingError("Non-numeric final topology coordinates at line " + str(line_number)) from exc
        _require(all(math.isfinite(x) for x in xyz), "Non-finite final topology coordinates")
        # PDB serial/residue fields can overflow into OpenMM's hexadecimal format
        # for bulk solvent. Atom identity here is row index, never PDB serial.
        atoms.append({"index": len(atoms), "name": line[12:16].strip(), "resname": line[17:20].strip(),
                      "chain": line[21].strip(), "resid": line[22:26].strip(), "icode": line[26].strip(),
                      "element": line[76:78].strip().upper(), "xyz_angstrom": xyz})
    return atoms


def _key(atom):
    return (str(atom["chain"]).strip(), str(atom.get("resid", atom.get("resseq"))).strip(),
            str(atom.get("icode", atom.get("insertion_code", ""))).strip(), atom.get("name", atom.get("atom_name")))


def _ranges(indices):
    result = []
    for index in sorted(indices):
        if result and index == result[-1][1] + 1:
            result[-1][1] = index
        else:
            result.append([index, index])
    return result


def _original_label(original):
    chain = str(original["chain"]).strip() or "<blank>"
    name = str(original["resname"]).strip() or "<blank>"
    return chain + ":" + name + str(original["resseq"]) + original.get("icode", "")


def add_original_identifiers(job, plan, paths):
    """Validate and save source->topology mapping, then annotate existing CSVs.

    Raises MappingError before any mapping output if the built solute cannot be
    identified exactly. Coordinate verification allows one uniform translation
    of the complete complex (PDB rounding tolerance 0.003 Angstrom), never an
    independent ligand transform. Bulk atoms are recorded as generated ranges.
    """
    job = Path(job).resolve()
    base = Path(paths["md"]) / "system"
    topology_pdb, topology_json = base / "topology.pdb", base / "topology.json"
    source_map_path = Path(plan["atom_map_path"])
    prep_path = Path(paths["md"]) / "prepared" / "protein_preparation.json"
    for path in (topology_pdb, topology_json, source_map_path, prep_path):
        _require(path.is_file(), "Original-identifier mapping requires artifact: " + str(path))
    final_atoms, meta, source_map, prep = _pdb_atoms(topology_pdb), _read(topology_json), _read(source_map_path), _read(prep_path)
    n = len(final_atoms)
    _require(n == meta.get("atoms"), "Topology PDB/metadata atom counts disagree")
    _require(len(meta.get("elements", [])) == n and len(meta.get("residues", [])) == n, "Topology metadata arrays have inconsistent lengths")
    for atom, element in zip(final_atoms, meta["elements"]):
        _require(atom["element"] == str(element).upper(), "Topology PDB/metadata elements disagree at index " + str(atom["index"]))
    protein_indices, ligand_indices = meta["protein_indices"], meta.get("ligand_indices", [])
    solute_indices = protein_indices + ligand_indices
    _require(all(type(i) is int and 0 <= i < n for i in solute_indices), "Invalid protein/ligand topology atom index")
    _require(len(set(solute_indices)) == len(solute_indices), "Protein/ligand topology indices overlap or repeat")
    source_rows = source_map["atoms"]
    source_by_id = {row["id"]: row for row in source_rows}
    _require(len(source_by_id) == len(source_rows), "Original atom IDs are duplicated")
    residue_definitions = {r["id"]: r for r in plan["residues"]}
    source_residue_data = {}
    for row in source_rows:
        original = row["original"]
        source_residue_data.setdefault(original["residue_id"], {key: original[key] for key in ("chain", "resseq", "icode", "resname", "model", "residue_id", "component_id")})
    protein_residue_keys = {}
    for residue in plan["residues"]:
        if residue.get("kind") == "protein":
            key = _key({**residue, "name": ""})[:3]
            _require(key not in protein_residue_keys, "Normalized protein residue key is ambiguous: " + str(key))
            protein_residue_keys[key] = residue["id"]
    original_protein_keys = {}
    original_kind = {}
    for row in source_rows:
        residue_id = row["original"]["residue_id"]
        kind = residue_definitions.get(residue_id, {}).get("kind", "excluded")
        original_kind[row["id"]] = kind
        if row["retained"] and kind == "protein":
            key = _key(row["normalized"])
            _require(key not in original_protein_keys, "Ambiguous normalized protein source atom identity")
            original_protein_keys[key] = row
    explicit_removed_keys = {tuple(record["atom_identity"]) for record in prep.get("explicit_chemical_removals", [])}
    added_heavy_keys = {tuple(key) for key in prep.get("added_heavy_atom_identities", [])}
    final_records, source_to_final, coordinate_pairs = {}, {}, []
    label_to_residue_ids = defaultdict(set)

    def add_final(index, kind, original_id, residue_ids, status, **extra):
        atom = final_atoms[index]
        label = meta["residues"][index]
        record = {"topology_index": index, "kind": kind, "element": atom["element"], "atom_name": atom["name"],
                  "final_residue_label": label, "original_atom_id": original_id,
                  "original_residue_ids": sorted(residue_ids), "identity_status": status, **extra}
        if original_id is not None:
            _require(original_id not in source_to_final, "One original atom maps to multiple topology atoms")
            row = source_by_id[original_id]
            _require(row["retained"], "Excluded original atom unexpectedly appears in topology")
            _require(row["original"]["element"].upper() == atom["element"], "Mapped atom element changed: " + original_id)
            source_to_final[original_id] = index
            coordinate_pairs.append((original_id, row["original"]["xyz"], atom["xyz_angstrom"]))
        final_records[index] = record
        label_to_residue_ids[label].update(residue_ids)

    seen_protein_keys = set()
    for index in protein_indices:
        atom = final_atoms[index]
        key = _key(atom)
        _require(key not in seen_protein_keys, "Built protein contains a repeated atom identity")
        seen_protein_keys.add(key)
        _require(key[:3] in protein_residue_keys, "Built protein residue identity differs from normalized input: " + str(key[:3]))
        residue_id = protein_residue_keys[key[:3]]
        source_row = original_protein_keys.get(key)
        if atom["element"] in {"H", "D"}:
            # The adapter deletes/rebuilds all protein H, so name agreement is
            # only a correspondence, never preservation of the original atom.
            correspondence = source_row["id"] if source_row and source_row["original"]["element"] in {"H", "D"} else None
            add_final(index, "protein", None, [residue_id], "regenerated_protein_hydrogen", name_correspondence_original_id=correspondence)
        elif source_row is not None:
            add_final(index, "protein", source_row["id"], [residue_id], "preserved_original_heavy_atom")
        else:
            _require(key in added_heavy_keys, "Unexpected new protein heavy atom without preparation audit: " + str(key))
            add_final(index, "protein", None, [residue_id], "audited_added_protein_heavy_atom")

    evidence = {"topology_pdb_sha256": _digest(topology_pdb), "topology_json_sha256": _digest(topology_json),
                "source_atom_map_sha256": _digest(source_map_path), "protein_preparation_sha256": _digest(prep_path)}
    if ligand_indices:
        chem_path = Path(plan.get("chemistry", {}).get("atom_map", ""))
        _require(chem_path.is_file(), "Ligand topology mapping requires the chemistry SDF atom map")
        chemistry_map = _read(chem_path)
        evidence["ligand_chemistry_map_sha256"] = _digest(chem_path)
        _require(len(chemistry_map) == len(ligand_indices), "Final ligand atom count differs from confirmed SDF atom map; untracked hydrogen addition/reordering is forbidden")
        by_sdf = {record["sdf_atom_index"]: record for record in chemistry_map}
        _require(set(by_sdf) == set(range(len(ligand_indices))), "SDF atom indices are duplicated, missing or non-contiguous")
        ligand_residues = {source_by_id[record["original_id"]]["original"]["residue_id"] for record in chemistry_map if record.get("original_id") in source_by_id}
        _require(bool(ligand_residues), "Ligand source residue mapping is empty")
        for sdf_index, index in enumerate(ligand_indices):
            record, final = by_sdf[sdf_index], final_atoms[index]
            _require(final["element"] == record["element"].upper(), "Ligand SDF/topology element order differs")
            expected_name = record["element"].title() + str(sdf_index + 1)
            _require(final["name"] == expected_name, "Ligand topology naming/order no longer matches the preserved executor contract: " + final["name"])
            original_id = record.get("original_id")
            if original_id is not None:
                _require(original_id in source_by_id and original_kind[original_id] == "ligand", "Chemistry atom map references an unknown/non-ligand original atom")
                residue_ids = [source_by_id[original_id]["original"]["residue_id"]]
                add_final(index, "ligand", original_id, residue_ids, "preserved_original_ligand_atom", sdf_atom_index=sdf_index)
            else:
                _require(record.get("added") is True and final["element"] in {"H", "D"}, "Untracked added ligand heavy atom")
                add_final(index, "ligand", None, ligand_residues, "explicit_chemical_definition_added_hydrogen", sdf_atom_index=sdf_index)
    else:
        _require(not plan.get("ligand_sdf"), "Confirmed ligand input is missing from built topology")

    source_ledger = []
    for row in source_rows:
        original_id, original = row["id"], row["original"]
        final_index = source_to_final.get(original_id)
        kind = original_kind[original_id]
        if final_index is not None:
            status = "mapped_to_topology"
        elif not row["retained"]:
            status = row["excluded_reason"]
        elif kind == "protein" and _key(row["normalized"]) in explicit_removed_keys:
            status = "explicitly_approved_chemical_removal"
        elif kind == "protein" and original["element"] in {"H", "D"}:
            status = "removed_before_protein_hydrogen_regeneration"
        elif kind == "water" and plan.get("decisions", {}).get("water_policy") == "replace_bulk":
            status = "explicitly_replaced_input_water"
        else:
            raise MappingError("Retained original atom was lost without an audited action: " + original_id)
        source_ledger.append({"original_atom_id": original_id, "topology_index": final_index, "status": status, "original": original})
    # Solvation may translate the entire complex. Enforce a single transform;
    # separate ligand placement or reordered coordinates cannot pass this test.
    translation = [0., 0., 0.]
    maximum_residual = 0.0
    if coordinate_pairs:
        _, first_before, first_after = coordinate_pairs[0]
        translation = [a - b for a, b in zip(first_after, first_before)]
        for original_id, before, after in coordinate_pairs:
            residual = math.dist([a - b for a, b in zip(after, before)], translation)
            maximum_residual = max(maximum_residual, residual)
            _require(residual <= .003, "Built system changed relative coordinates of original atom " + original_id + "; mapping cannot certify preserved pose")
    bulk_indices = sorted(set(range(n)) - set(solute_indices))
    report = {"schema_version": "nexus-original-identifiers-2.0", "topology_index_base": 0, "coordinate_unit": "angstrom",
              "topology_atom_count": n, "solute_atom_count": len(solute_indices), "generated_bulk_atom_count": len(bulk_indices),
              "generated_bulk_index_ranges_inclusive": _ranges(bulk_indices), "evidence": evidence, "source": source_map.get("source"),
              "source_atoms": source_ledger, "solute_atoms": [final_records[index] for index in sorted(final_records)],
              "residue_mapping": {label: {"original_residue_ids": sorted(ids),
                                           "original_labels": [_original_label(source_residue_data[rid]) for rid in sorted(ids)]}
                                   for label, ids in sorted(label_to_residue_ids.items())},
              "uniform_translation_angstrom": translation, "maximum_relative_coordinate_residual_angstrom": maximum_residual,
              "protein_hydrogen_policy": "All input protein H were removed/rebuilt; name correspondence does not assert atom identity.",
              "valid_for_pre_dynamics_gate": True, "verification_scope": "Built-system files only; no MD or trajectory was run by this mapping function."}
    mapping_path = job / "mappings" / "topology_atom_map.json"
    _write(mapping_path, report)

    def annotation(label):
        _require(label in label_to_residue_ids, "Analysis residue label has no verified original mapping: " + label)
        ids = sorted(label_to_residue_ids[label])
        return {"original_residue_ids": json.dumps(ids, ensure_ascii=False),
                "original_labels": json.dumps([_original_label(source_residue_data[rid]) for rid in ids], ensure_ascii=False),
                "original_chains": json.dumps([source_residue_data[rid]["chain"] for rid in ids], ensure_ascii=False),
                "original_resseq": json.dumps([source_residue_data[rid]["resseq"] for rid in ids]),
                "original_icodes": json.dumps([source_residue_data[rid]["icode"] for rid in ids]),
                "original_resnames": json.dumps([source_residue_data[rid]["resname"] for rid in ids])}

    table_fields = {"rmsf.csv": ["residue"], "contact_occupancy.csv": ["residue"],
                    "contact_map.csv": ["residue_A", "residue_B"], "salt_bridge_occupancy.csv": ["residue_A", "residue_B"],
                    "hbond_occupancy.csv": ["donor_residue", "acceptor_residue"], "Hbond.csv": ["donor_residue", "acceptor_residue"]}
    exports = []
    analysis_dir = Path(paths["analysis"])
    for source_csv in sorted(analysis_dir.glob("replica_*/*.csv")):
        if source_csv.name not in table_fields:
            continue
        with source_csv.open(newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle)
            fieldnames, rows = list(reader.fieldnames or []), list(reader)
        if not fieldnames:
            continue
        residue_fields = table_fields[source_csv.name]
        _require(set(residue_fields) <= set(fieldnames), "Analysis CSV schema changed: " + source_csv.name)
        new_fields = list(fieldnames)
        for field in residue_fields:
            for suffix in ("original_residue_ids", "original_labels", "original_chains", "original_resseq", "original_icodes", "original_resnames"):
                new_fields.append(field + "_" + suffix)
        is_hbond = source_csv.name in {"hbond_occupancy.csv", "Hbond.csv"}
        if is_hbond:
            for role in ("donor", "acceptor"):
                new_fields.extend([role + "_original_atom_id", role + "_identity_status", role + "_original_atom_name", role + "_original_serial"])
        for row in rows:
            for field in residue_fields:
                row.update({field + "_" + suffix: value for suffix, value in annotation(row[field]).items()})
            if is_hbond:
                for role in ("donor", "acceptor"):
                    index = int(row[role + "_index"])
                    _require(index in final_records, "H-bond atom index has no solute original mapping")
                    atom = final_records[index]
                    _require(atom["final_residue_label"] == row[role + "_residue"], "H-bond index/residue label disagreement")
                    original = source_by_id[atom["original_atom_id"]]["original"] if atom["original_atom_id"] else {}
                    row[role + "_original_atom_id"] = atom["original_atom_id"] or ""
                    row[role + "_identity_status"] = atom["identity_status"]
                    row[role + "_original_atom_name"] = original.get("atom_name", "")
                    row[role + "_original_serial"] = original.get("serial", "")
        target_csv = source_csv.with_name(source_csv.stem + "_original.csv")
        temporary = target_csv.with_name(target_csv.name + "." + uuid.uuid4().hex + ".tmp")
        with temporary.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=new_fields)
            writer.writeheader()
            writer.writerows(rows)
        temporary.replace(target_csv)
        exports.append({"source": str(source_csv), "source_sha256": _digest(source_csv), "output": str(target_csv), "rows": len(rows)})
    export_report = {"mapping": str(mapping_path), "mapping_sha256": _digest(mapping_path), "exports": exports,
                     "note": "Original analysis columns/units are preserved; appended columns reference the unmodified source PDB."}
    _write(job / "mappings" / "analysis_original_identifiers.json", export_report)
    return {"status": "PASS", "mapping_path": str(mapping_path), "mapped_original_atoms": len(source_to_final),
            "source_atom_count": len(source_rows), "analysis_tables_written": len(exports),
            "maximum_relative_coordinate_residual_angstrom": maximum_residual}
